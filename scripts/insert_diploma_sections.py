def insert_paragraph_before(
    paragraph: Paragraph, text: str = "", style: str | None = None
) -> Paragraph:
    new_p = OxmlElement("w:p")
    paragraph._p.addprevious(new_p)
    new_para = Paragraph(new_p, paragraph._parent)
    if text:
        new_para.add_run(text)
    if style:
        new_para.style = style
    return new_para


def insert_blocks_before(anchor: Paragraph, blocks: list[tuple[str, str]]) -> None:
    """blocks: list of (style_name, text) in document order (first item ends up closest to anchor)."""
    current = anchor
    for style, text in reversed(blocks):
        current = insert_paragraph_before(current, text, style)


