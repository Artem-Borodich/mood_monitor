def find_anchor(doc: Document) -> Paragraph:
    for p in doc.paragraphs:
        t = p.text.strip()
        if t.startswith("1.2 Выбор средств"):
            return p
    raise RuntimeError("Anchor paragraph '1.2 Выбор средств...' not found")


def renumber_old_sections(doc: Document) -> None:
    for p in doc.paragraphs:
        t = p.text.strip()
        if t.startswith("1.2 Выбор средств"):
            p.text = t.replace("1.2 ", "1.4 ", 1)
        elif t.startswith("1.3 Выбор средств"):
            p.text = t.replace("1.3 ", "1.5 ", 1)


def update_toc_lines(doc: Document) -> None:
    replacements = {
        "1.2 Выбор средств для разработки клиентской части приложения": (
            "1.2 Обзор аналогов\n"
            "1.3 Функциональные и нефункциональные требования\n"
            "1.4 Выбор средств для разработки клиентской части приложения"
        ),
        "1.3 Выбор средств для разработки серверной части приложения": (
            "1.5 Выбор средств для разработки серверной части приложения"
        ),
    }
    for p in doc.paragraphs:
        for old, new in replacements.items():
            if old in p.text:
                p.text = p.text.replace(old, new)


def main() -> None:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    paths = glob.glob(os.path.join(root, "*.docx"))
    if not paths:
        raise SystemExit("No .docx in project root")
    path = paths[0]

    backup = path + ".bak_" + datetime.now().strftime("%Y%m%d_%H%M%S")
    shutil.copy2(path, backup)
    print("Backup:", backup)

    doc = Document(path)
    anchor = find_anchor(doc)
    insert_blocks_before(anchor, NEW_SECTIONS)
    renumber_old_sections(doc)
    update_toc_lines(doc)

    doc.save(path)
    print("Updated:", path)
    print("Inserted", len(NEW_SECTIONS), "paragraphs before former section 1.2.")


if __name__ == "__main__":
    main()
